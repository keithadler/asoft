rows = []
for code in range(0x20, 0x60):
    ch = chr(code)
    art = G.get(ch)
    if art is None:
        raise SystemExit("no glyph for %r ($%02X)" % (ch, code))
    cells = art.split()
    if len(cells) != 7 or any(len(r) != 5 for r in cells):
        raise SystemExit("glyph %r is not 5x7" % ch)
    # one byte per scan line, bit 4 leftmost, then a blank eighth line
    bits = [int(r.replace('.', '0').replace('#', '1'), 2) for r in cells] + [0]
    rows.append((ch, bits))

